def completion(content):
    return {
        'id': 'validation-model',
        'object': 'chat.completion',
        'created': 1794873600,
        'model': MODEL_NAME,
        'choices': [{
            'index': 0,
            'message': {'role': 'assistant', 'content': json.dumps(content, ensure_ascii=False)},
            'finish_reason': 'stop',
        }],
        'usage': {'prompt_tokens': 12, 'completion_tokens': 8, 'total_tokens': 20},
    }


class ValidationModel:
    def __init__(self, vector, observations, requests_log):
        self.vector = vector
        self.observations = observations
        self.requests_log = requests_log
        self.lock = threading.Lock()

    def respond(self, request):
        value = extract_task_input(request)
        if 'draft' in value and 'targets' in value:
            output = authoring_output(value)
            kind = 'report_authoring'
            stable_id = value['draft']['draft_id']
        else:
            output, stable_id = summary_output(self.vector, value)
            kind = 'project_summary'
        with self.lock:
            with self.observations.open('a', encoding='utf-8') as stream:
                stream.write(json.dumps({
                    'kind': kind,
                    'inputSha256': hashlib.sha256(canonical_bytes(value)).hexdigest(),
                    'stableId': stable_id,
                    'recordedAt': datetime.now(UTC).isoformat(),
                }, sort_keys=True) + '\n')
        return completion(output)

    def record_request(self, value):
        with self.lock:
            with self.requests_log.open('a', encoding='utf-8') as stream:
                stream.write(json.dumps(value, sort_keys=True) + '\n')


def extract_task_input(request):
    for candidate in task_input_candidates(request):
        return candidate
    raise ValueError('No task input JSON found in model request.')


def task_input_candidates(value):
    if isinstance(value, dict):
        if 'binding' in value or 'draft' in value:
            yield value
            return
        for item in value.values():
            yield from task_input_candidates(item)
    elif isinstance(value, list):
        for item in value:
            yield from task_input_candidates(item)
    elif isinstance(value, str):
        for candidate in json_object_candidates(value):
            try:
                parsed = json.loads(candidate)
            except (TypeError, ValueError):
                continue
            yield from task_input_candidates(parsed)


def content_candidates(content):
    if isinstance(content, str):
        yield content
        start, end = content.find('{'), content.rfind('}')
        if 0 <= start < end:
            yield content[start:end + 1]
    elif isinstance(content, list):
        for item in content:
            if isinstance(item, dict):
                yield from content_candidates(item.get('text'))


def json_object_candidates(text):
    yield text
    decoder = json.JSONDecoder()
    for index, char in enumerate(text):
        if char != '{':
            continue
        try:
            _, end = decoder.raw_decode(text[index:])
        except ValueError:
            continue
        yield text[index:index + end]


def authoring_output(value):
    evidence = value.get('evidence') or ()
    default_refs = [row['ref_id'] for row in evidence if isinstance(row, dict) and isinstance(row.get('ref_id'), str)]
    outputs = []
    for target in value['targets']:
        refs = [
            row['ref_id'] for row in evidence
            if isinstance(row, dict) and row.get('source_key') == target.get('source_key')
        ] or default_refs[:1]
        outputs.append({
            'target_id': target['target_id'],
            'status': 'filled',
            'fragment': plain_text_fragment('Synthetic validation note generated by the loopback model.'),
            'evidence_refs': refs,
            'reason_code': None,
        })
    return {'schema_version': 1, 'targets': outputs}


def plain_text_fragment(text):
    return {
        'schema_version': 2,
        'blocks': [{
            'type': 'paragraph',
            'content': [{
                'type': 'text',
                'text': text,
                'marks': [],
                'foreground': None,
                'background': None,
            }],
        }],
    }


class Handler(BaseHTTPRequestHandler):
    model = None

    def setup(self):
        super().setup()
        self.connection.settimeout(READ_TIMEOUT_SECONDS)

    def do_GET(self):
        path = urlsplit(self.path).path
        self.model.record_request({'method': 'GET', 'path': path})
        if path == '/health':
            self._json(200, {'status': 'ok'})
            return
        self._json(404, {'error': 'not_found'})

    def do_POST(self):
        path = urlsplit(self.path).path
        if path != '/v1/chat/completions':
            self.model.record_request({'method': 'POST', 'path': path, 'status': 404})
            self._json(404, {'error': 'not_found'})
            return
        try:
            length = self._content_length()
            raw = self.rfile.read(length)
            request = json.loads(raw.decode('utf-8'))
            self.model.record_request({
                'method': 'POST',
                'path': path,
                'status': 'received',
                'content_length': length,
                'request_keys': sorted(request) if isinstance(request, dict) else None,
                'messages': message_diagnostics(request),
            })
            self._json(200, self.model.respond(request))
        except ValueError as error:
            status = 413 if str(error) == 'request_too_large' else 400
            self.model.record_request({'method': 'POST', 'path': path, 'status': status, 'error': str(error)})
            self._json(status, {'error': {'message': str(error), 'type': 'synthetic_model_error'}})
        except (TimeoutError, socket.timeout):
            self.model.record_request({'method': 'POST', 'path': path, 'status': 408, 'error': 'request_timeout'})
            self._json(408, {'error': {'message': 'request_timeout', 'type': 'synthetic_model_error'}})
        except Exception as error:
            self.model.record_request({'method': 'POST', 'path': path, 'status': 500, 'error': type(error).__name__})
            self._json(500, {'error': {'message': type(error).__name__, 'type': 'synthetic_model_error'}})

    def log_message(self, format, *args):
        return

    def _json(self, status, value):
        body = json.dumps(value, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
        self.send_response(status)
        self.send_header('Content-Type', 'application/json')
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _content_length(self):
        raw = self.headers.get('Content-Length')
        try:
            length = int(raw)
        except (TypeError, ValueError):
            raise ValueError('invalid_content_length') from None
        if length < 0:
            raise ValueError('invalid_content_length')
        if length > MAX_REQUEST_BYTES:
            raise ValueError('request_too_large')
        return length


def message_diagnostics(request):
    if not isinstance(request, dict):
        return None
    result = []
    for message in request.get('messages', ()):
        if not isinstance(message, dict):
            continue
        content = message.get('content')
        text = content if isinstance(content, str) else json.dumps(content, ensure_ascii=False) if content is not None else ''
        result.append({
            'role': message.get('role'),
            'content_sha256': hashlib.sha256(text.encode('utf-8')).hexdigest(),
            'content_prefix': text[:400],
            'content_suffix': text[-400:],
        })
    return result


class BoundedThreadingHTTPServer(ThreadingHTTPServer):
    daemon_threads = True
    block_on_close = False


def serve(args):
    run_dir = args.run_dir.resolve(strict=True)
    stop = args.stop_file.resolve()
    vector = json.loads(args.fixture.read_text(encoding='utf-8'))
    Handler.model = ValidationModel(
        vector,
        run_dir / 'model' / 'executor-observations.jsonl',
        run_dir / 'model' / 'model-requests.jsonl',
    )
    server = BoundedThreadingHTTPServer(('127.0.0.1', args.port), Handler)
    connection = {
        'schema_version': 1,
        'qualification': 'loopback_openai_compatible',
        'pid': os.getpid(),
        'base_url': f'http://127.0.0.1:{args.port}/v1',
        'model': MODEL_NAME,
        'api_key': API_KEY,
        'stop_file': str(stop),
        'launch_id': args.launch_id,
        'exit_file': str(args.exit_file.resolve()),
    }
    pending = args.connection_file.resolve().with_name(f'{args.connection_file.name}.tmp')
    pending.write_text(json.dumps(connection, sort_keys=True), encoding='utf-8')
    pending.replace(args.connection_file.resolve())
    thread = threading.Thread(target=server.serve_forever, name='validation-model-http', daemon=True)
    thread.start()
    deadline = time.monotonic() + args.lifetime_seconds
    try:
        while not stop.exists() and time.monotonic() < deadline:
            time.sleep(0.05)
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--run-dir', type=Path, required=True)
    parser.add_argument('--fixture', type=Path, required=True)
    parser.add_argument('--stop-file', type=Path, required=True)
    parser.add_argument('--connection-file', type=Path, required=True)
    parser.add_argument('--exit-file', type=Path, required=True)
    parser.add_argument('--launch-id', required=True)
    parser.add_argument('--port', type=int, required=True)
    parser.add_argument('--lifetime-seconds', type=int, required=True)
    args = parser.parse_args()
    code = 0
    try:
        serve(args)
    except SystemExit as error:
        code = error.code if type(error.code) is int else 1
    except BaseException:
        code = 1
        raise
    finally:
        write_exit_receipt(args.exit_file, service='scripted-model', launch_id=args.launch_id,
                           pid=os.getpid(), exit_code=code)
    return code


if __name__ == '__main__':
    raise SystemExit(main())
