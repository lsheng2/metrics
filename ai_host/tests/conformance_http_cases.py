from urllib.parse import urlsplit

import pytest

from ai_base_runtime import request_body_policy
from ai_host.tests.conformance_host_cases import identity_package


@pytest.mark.parametrize('length_kind', ['over_limit', 'invalid'])
def test_waitress_rejects_invalid_length_before_auth_or_body_delivery(
    ai_host_mode, ai_host_factory, ai_server_factory, ai_clock_and_limits, length_kind,
):
    visits = []
    package = identity_package(visits)
    limit = request_body_policy(ai_clock_and_limits.settings, (package,)).max_request_body_bytes
    with ai_host_factory(
        settings=ai_clock_and_limits.settings, config=ai_clock_and_limits.config,
        apps=(package,), start_timeout=15.0,
    ) as session:
        with ai_server_factory(session) as server:
            response = server.request(
                'POST', server.root_path + '/apps/probe/api/identity',
                headers=(
                    ('Host', urlsplit(server.base_url).netloc),
                    ('Content-Type', 'application/json'),
                    ('Content-Length', str(limit + 1) if length_kind == 'over_limit' else 'invalid'),
                ),
                timeout=2,
            )
            assert response.status == (413 if length_kind == 'over_limit' else 400)
            assert b'(generated by waitress)' in response.body
            assert not visits


def test_exact_global_body_limit_reaches_authentication(
    ai_host_mode, ai_host_factory, ai_server_factory, ai_clock_and_limits,
):
    visits = []
    package = identity_package(visits)
    limit = request_body_policy(ai_clock_and_limits.settings, (package,)).max_request_body_bytes
    with ai_host_factory(
        settings=ai_clock_and_limits.settings, config=ai_clock_and_limits.config,
        apps=(package,), start_timeout=15.0,
    ) as session:
        with ai_server_factory(session) as server:
            response = server.request(
                'POST', server.root_path + '/apps/probe/api/identity',
                headers=(('Host', urlsplit(server.base_url).netloc), ('Content-Type', 'application/json')),
                body=b' ' * (limit - 2) + b'{}', timeout=3,
            )
            assert response.status == 401
            assert b'(generated by waitress)' not in response.body
            assert not visits
