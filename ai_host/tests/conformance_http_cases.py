@pytest.mark.parametrize('authenticated', [False, True])
def test_chunked_overflow_is_rejected_by_waitress_before_app_admission(
    ai_host_mode, ai_host_factory, ai_server_factory, ai_clock_and_limits, ai_credentials, authenticated,
):
    with host_probe(ai_host_factory, ai_server_factory, ai_clock_and_limits) as (probe, session, server):
        address = urlsplit(server.base_url)
        connection = HTTPConnection(address.hostname, address.port, timeout=5)
        request_headers = {'Host': address.netloc, 'Content-Type': 'application/json'}
        if authenticated:
            request_headers.update(ai_credentials.headers(ai_credentials.owner))
        try:
            connection.putrequest('POST', path(server, 'body'), skip_host=True)
            for name, value in request_headers.items():
                connection.putheader(name, value)
            connection.putheader('Transfer-Encoding', 'chunked')
            connection.endheaders()
            for _ in range(128):
                connection.send(b'10000\r\n' + b'x' * 65536 + b'\r\n')
            # Wait for early rejection at N+1, without sending unread trailing
            # chunks that can reset the TCP connection before its 413 body.
            connection.send(b'1\r\nx')
            response = connection.getresponse()
            assert response.status == 413
            assert b'(generated by waitress)' in response.read()
        finally:
            connection.close()
        assert probe.count('echo') == 0
        assert session.handle.blocking.diagnostics.snapshot(ai_credentials.owner, timeout=1).short_in_flight_count == 0


def test_incomplete_body_never_reaches_the_application_or_short_quota(
    ai_host_mode, ai_host_factory, ai_server_factory, ai_clock_and_limits, ai_credentials,
):
    with host_probe(ai_host_factory, ai_server_factory, ai_clock_and_limits) as (probe, session, server):
        address = urlsplit(server.base_url)
        connections = []
        try:
            for _ in range(6):
                connection = HTTPConnection(address.hostname, address.port, timeout=3)
                connections.append(connection)
                connection.putrequest('POST', path(server, 'body'), skip_host=True)
                for name, value in auth_headers(server, ai_credentials):
                    connection.putheader(name, value)
                connection.putheader('Content-Length', '100')
                connection.putheader('Content-Type', 'application/json')
                connection.endheaders(b'{')
            time.sleep(0.05)
            assert probe.count('echo') == 0
            assert session.handle.blocking.diagnostics.snapshot(ai_credentials.owner, timeout=1).short_in_flight_count == 0
            response = server.request('GET', path(server, 'echo'), headers=auth_headers(server, ai_credentials), timeout=2)
            assert response.status == 200
            assert probe.count('echo') == 1
        finally:
            for connection in connections:
                connection.close()
        assert probe.count('echo') == 1
