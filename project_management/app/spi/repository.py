from typing import Protocol

from ..domain.contracts import ProjectActor, ProjectDetail, ProjectSummary, ScopeDescriptor, ScopeSelection, StageSummary


class ProjectRepository(Protocol):
    def create(self, actor: ProjectActor, key: str, name: str) -> ProjectSummary: ...
    def list(self, actor: ProjectActor, limit: int, offset: int) -> tuple[ProjectSummary, ...]: ...
    def get(self, actor: ProjectActor, project_id: str) -> ProjectDetail: ...
    def add_stage(self, actor: ProjectActor, project_id: str, key: str, name: str,
                  selection: ScopeSelection, descriptor: ScopeDescriptor) -> StageSummary: ...
    def archive(self, actor: ProjectActor, project_id: str) -> ProjectSummary: ...
